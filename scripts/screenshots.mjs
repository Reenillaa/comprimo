// Regenerates docs/screenshots from the production build (needs `npm run preview` running on :4173).
import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://127.0.0.1:4173/');
await p.waitForTimeout(900);
await p.screenshot({ path: 'docs/screenshots/empty-desktop.png' });
await p.getByTestId('file-input').setInputFiles(['photo-large.jpg', 'photo-exif.jpg', 'alpha.png', 'flat-graphic.png', 'photo.webp', 'photo.avif', 'photo.png', 'fake.jpg'].map((f) => 'tests/fixtures/' + f));
await p.waitForTimeout(1500);
await p.screenshot({ path: 'docs/screenshots/processing.png' });
await p.waitForFunction(() => document.querySelectorAll('[data-testid=file-row]:is([data-status=done],[data-status=error])').length === 8, null, { timeout: 120000 });
await p.waitForTimeout(400);
await p.screenshot({ path: 'docs/screenshots/results-desktop.png' });
await p.waitForTimeout(1500);
await p.getByRole('radio', { name: 'Lista' }).check();
await p.waitForTimeout(500);
await p.screenshot({ path: 'docs/screenshots/results-list.png' });
await p.getByRole('radio', { name: 'Cuadrícula' }).check();
await p.getByRole('button', { name: 'Comparar photo-exif.jpg' }).click();
await p.waitForTimeout(600);
await p.screenshot({ path: 'docs/screenshots/compare.png' });
await p.keyboard.press('Escape');
await p.getByRole('button', { name: 'Cambiar a tema claro' }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'docs/screenshots/results-light.png' });
await p.getByRole('button', { name: 'Cambiar a tema oscuro' }).click();
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(400);
await p.screenshot({ path: 'docs/screenshots/results-mobile.png', fullPage: true });
await b.close();
console.log('ok');
